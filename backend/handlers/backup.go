func quoteIdent(name string) string {
	return "`" + strings.ReplaceAll(name, "`", "``") + "`"
}

// quoteString renders a value as a single-quoted SQL string literal, escaping
// embedded quotes the standard way ('→”).
func quoteString(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}

// formatSQLValue renders a scanned column value as a valid SQL literal for the
// dump. Strings/bytes are quoted and escaped; time.Time is emitted as a quoted
// timestamp (Go's default %v formatting is not valid SQL and breaks restore).
// Any unexpected type falls back to a quoted string literal so it can never
// produce malformed or injectable SQL.
func formatSQLValue(val interface{}) string {
	switch v := val.(type) {
	case nil:
		return "NULL"
	case string:
		return quoteString(v)
	case []byte:
		return quoteString(string(v))
	case time.Time:
		return quoteString(v.Format("2006-01-02 15:04:05.999999999-07:00"))
	case bool:
		if v {
			return "1"
		}
		return "0"
	case int64:
		return strconv.FormatInt(v, 10)
	case float64:
		return strconv.FormatFloat(v, 'g', -1, 64)
	default:
		return quoteString(fmt.Sprintf("%v", v))
	}
}

// dumpExcludedTables lists tables omitted from logical SQL dumps.
var dumpExcludedTables = map[string]bool{
	"users": true,
}

// generateSQLDump creates a SQL dump of the SQLite database
func generateSQLDump(db *sql.DB) (string, error) {
	var sqlDump strings.Builder

	sqlDump.WriteString("-- Home Media Database Backup\n")
	sqlDump.WriteString("-- Generated by Home Media\n\n")

	tableQuery := `SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name;`
	rows, err := db.Query(tableQuery)
	if err != nil {
		return "", err
	}
	defer rows.Close()

	var tables []string
	for rows.Next() {
		var tableName string
		if err := rows.Scan(&tableName); err != nil {
			return "", err
		}
		if dumpExcludedTables[tableName] {
			continue
		}
		tables = append(tables, tableName)
	}

	for _, tableName := range tables {
		var createSQL string
		err := db.QueryRow("SELECT sql FROM sqlite_master WHERE type='table' AND name=?;", tableName).Scan(&createSQL)
		if err != nil {
			return "", err
		}

		sqlDump.WriteString(fmt.Sprintf("-- Table: %s\n", tableName))
		sqlDump.WriteString("DROP TABLE IF EXISTS " + quoteIdent(tableName) + ";\n")
		sqlDump.WriteString(createSQL + ";\n\n")

		dataRows, err := db.Query("SELECT * FROM " + quoteIdent(tableName) + ";")
		if err != nil {
			return "", err
		}

		columns, err := dataRows.Columns()
		if err != nil {
			dataRows.Close()
			return "", err
		}

		for dataRows.Next() {
			values := make([]interface{}, len(columns))
			valuePtrs := make([]interface{}, len(columns))
			for i := range values {
				valuePtrs[i] = &values[i]
			}

			if err := dataRows.Scan(valuePtrs...); err != nil {
				dataRows.Close()
				return "", err
			}

			sqlDump.WriteString("INSERT INTO " + quoteIdent(tableName) + " (")
			for i, col := range columns {
				if i > 0 {
					sqlDump.WriteString(", ")
				}
				sqlDump.WriteString(quoteIdent(col))
			}
			sqlDump.WriteString(") VALUES (")

			for i, val := range values {
				if i > 0 {
					sqlDump.WriteString(", ")
				}
				sqlDump.WriteString(formatSQLValue(val))
			}
			sqlDump.WriteString(");\n")
		}
		dataRows.Close()
		sqlDump.WriteString("\n")
	}

	return sqlDump.String(), nil
}

// createFileBackup creates a physical copy of the database file
func createFileBackup(cfg *config.Config) (string, error) {
	if err := os.MkdirAll(cfg.BackupPath, 0755); err != nil {
		return "", fmt.Errorf("failed to create backup directory: %w", err)
	}

	timestamp := time.Now().Format("20060102_150405") // YYYYMMDD_HHMMSS
	filename := fmt.Sprintf("media_backup_%s.db", timestamp)
	backupFilePath := filepath.Join(cfg.BackupPath, filename)

	// VACUUM INTO produces a transactionally-consistent snapshot of the live
	// database through the existing connection, avoiding the corruption risk of
	// copying the active SQLite file. The target file must not already exist,
	// which the timestamped filename guarantees.
	if err := database.DB.Exec("VACUUM INTO ?", backupFilePath).Error; err != nil {
		return "", fmt.Errorf("failed to create database backup: %w", err)
	}

	return filename, nil
}

// CreateDatabaseBackup generates a SQL dump of the database
func CreateDatabaseBackup(c *gin.Context) {
	sqlDB, err := database.DB.DB()
	if err != nil {
		helpers.RespondInternalError(c, "Failed to get database connection", err.Error())
		return
	}

	sqlDump, err := generateSQLDump(sqlDB)
	if err != nil {
		helpers.RespondInternalError(c, "Failed to generate database backup", err.Error())
		return
	}

	helpers.RespondWithSuccess(c, gin.H{
		"sql_dump": sqlDump,
	})
}

// CreateFileBackup creates a physical copy of the database file
func CreateFileBackup(c *gin.Context) {
	cfg := config.Load()

	backupFilename, err := createFileBackup(cfg)
	if err != nil {
		helpers.RespondInternalError(c, "Failed to create file backup", err.Error())
		return
	}

	helpers.RespondWithSuccess(c, gin.H{
		"backup_filename": backupFilename,
	})
}

// ExportMediaToCSV exports all media to CSV format
func ExportMediaToCSV(c *gin.Context) {
	var media []models.Media

	result := helpers.GetMediaWithPreloads(database.DB).Find(&media)

	if result.Error != nil {
		helpers.RespondInternalError(c, "Failed to fetch media data", result.Error.Error())
		return
	}

	filename := "media-collection-" + time.Now().Format("2006-01-02") + ".csv"
	c.Header("Content-Type", "text/csv")
	c.Header("Content-Disposition", "attachment; filename="+filename)

	writer := csv.NewWriter(c.Writer)
	defer writer.Flush()

	header := []string{
		"ID", "Title", "Media Type", "Content Type", "Availability",
		"EAN", "Audio", "Subtitles",
		"Edition", "Watched", "Rating", "Watch Notes", "Notes",
		"Additional Media", "Created At", "Updated At",
	}
	if err := writer.Write(header); err != nil {
		helpers.RespondInternalError(c, "Failed to write CSV header", err.Error())
		return
	}

	for _, item := range media {
		var audioList []string
		for _, audio := range item.Audio {
			audioList = append(audioList, audio.Flag+" "+audio.Label)
		}
		audioStr := strings.Join(audioList, ", ")

		var subtitlesList []string
		for _, subtitle := range item.Subtitles {
			subtitlesList = append(subtitlesList, subtitle.Flag+" "+subtitle.Label)
		}
		subtitlesStr := strings.Join(subtitlesList, ", ")

		watchedStr := "No"
		if item.Watched {
			watchedStr = "Yes"
		}

		ratingStr := ""
		if item.Rating != nil {
			ratingStr = strconv.Itoa(*item.Rating)
		}

		record := []string{
			strconv.Itoa(int(item.ID)),
			item.Title,
			getOptionLabel(item.MediaType),
			getOptionLabel(item.ContentType),
			getOptionLabel(item.Availability),
			item.EAN,
			audioStr,
			subtitlesStr,
			getOptionLabel(item.Edition),
			watchedStr,
			ratingStr,
			item.WatchNotes,
			item.Notes,
			item.AdditionalMedia,
			item.CreatedAt.Format("2006-01-02 15:04:05"),
			item.UpdatedAt.Format("2006-01-02 15:04:05"),
		}

		if err := writer.Write(record); err != nil {
			helpers.RespondInternalError(c, "Failed to write CSV record", err.Error())
			return
		}
	}
}

// getOptionLabel returns the label for various option types
func getOptionLabel(option interface{}) string {
	if option == nil {
		return ""
	}

	switch v := option.(type) {
	case models.MediaType:
		return v.Label
	case models.ContentType:
		return v.Label
	case models.AvailabilityOption:
		return v.Label
	case models.LanguageOption:
		return v.Label
	case models.EditionOption:
		return v.Label
	default:
		return ""
	}
}
